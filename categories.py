OTHER = "Разное"

# В каком порядке показывать категории на страницах.
ORDER = [label for label, _ in RULES] + [OTHER]

_COMPILED = [(label, re.compile(pattern)) for label, pattern in RULES]


def classify(name: str) -> str:
    low = (name or "").lower()
    for label, pattern in _COMPILED:
        if pattern.search(low):
            return label
    return OTHER
